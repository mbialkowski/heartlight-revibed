#!/usr/bin/env python3
"""Annotated disassembly of HL.EXE (16-bit real mode) using capstone.

* code segments are disassembled linearly, restarting at every known code address (symbols,
  jump-table targets) so that inline data does not desynchronise the listing;
* Borland switch tables (`cmp bx, N` ... `jmp word ptr cs:[bx + T]`) are detected and printed
  as `dw` lists with their case numbers;
* immediates pointing at strings in DGROUP are annotated, far/near calls get symbol names.

    python3 tools/disasm.py HL.EXE -o reference/hl.asm [-s tools/symbols.txt]
"""
import argparse
import os
import re
import struct
import sys

import capstone

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from mz_loader import MZ  # noqa: E402

DGROUP = 0x214D          # Borland DGROUP (DS) at load segment 0x1000
CODE_END = 0x213D        # segments below this hold code (213D: tail stubs; 214D: data)

GRID = {0x4C69: 'pending', 0x4D9D: 'frame', 0x4ED1: 'state', 0x5005: 'type'}
GRID_REF = re.compile(r'\[(?:bx \+ )?(?:si|di|bx)(?: \+ si| \+ di)? \+ (0x[0-9a-f]+)\]')


def grid_note(op_str):
    """[di + 0x501b] -> type[i+22]: accesses to the 22x14 level arrays"""
    m = GRID_REF.search(op_str)
    if not m:
        return None
    v = int(m.group(1), 16)
    for base, name in GRID.items():
        d = v - base
        if -46 <= d <= 46:
            return f'{name}[i{d:+d}]' if d else f'{name}[i]'
    return None


JMP_TABLE = re.compile(r'word ptr cs:\[bx \+ (0x[0-9a-f]+)\]')
CMP_BX = re.compile(r'^bx, (0x[0-9a-f]+|\d+)$')


def load_symbols(path):
    syms, notes = {}, {}
    if path and os.path.exists(path):
        for line in open(path):
            body, _, comment = line.partition('#')
            body = body.strip()
            if not body:
                continue
            addr, name = body.split()[:2]
            seg, off = addr.split(':')
            syms[(int(seg, 16), int(off, 16))] = name
            if comment.strip():
                notes[(int(seg, 16), int(off, 16))] = comment.strip()
    return syms, notes


def dgroup_strings(mz):
    base = mz.lin(DGROUP, 0)
    data = mz.image[base:]
    out = {}
    for m in re.finditer(rb'[\x20-\x7e\r\n]{3,}\x00', data):
        out[m.start()] = m.group()[:-1].decode('latin1').replace('\r', '\\r').replace('\n', '\\n')
    return out


def find_tables(md, code):
    """returns {table_offset: n_entries} and the set of case targets"""
    tables, targets = {}, set()
    window = []
    for ins in md.disasm(code, 0):
        m = JMP_TABLE.search(ins.op_str) if ins.mnemonic == 'jmp' else None
        if m:
            t = int(m.group(1), 16)
            n = None
            for prev in reversed(window):
                c = CMP_BX.match(prev.op_str) if prev.mnemonic == 'cmp' else None
                if c:
                    n = int(c.group(1), 0) + 1
                    break
            if n and t + 2 * n <= len(code):
                tables[t] = n
                for i in range(n):
                    targets.add(struct.unpack_from('<H', code, t + 2 * i)[0])
        window = (window + [ins])[-8:]
    return tables, targets


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('exe')
    ap.add_argument('-o', '--out', default='-')
    ap.add_argument('-s', '--symbols', default=os.path.join(os.path.dirname(__file__), 'symbols.txt'))
    a = ap.parse_args()
    mz = MZ(a.exe)
    syms, notes = load_symbols(a.symbols)
    strs = dgroup_strings(mz)
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_16)
    md.skipdata = True
    out = sys.stdout if a.out == '-' else open(a.out, 'w')
    out.write('; HL.EXE (Heartlight PC, 2006 CC release) - annotated disassembly\n'
              '; generated by tools/disasm.py - do not edit, add names to tools/symbols.txt\n'
              f'; load segment 1000, DGROUP (DS) = {DGROUP:04X}; addresses are seg:off\n')
    segs = [s for s in mz.segments if s < CODE_END] + [CODE_END]
    for si, seg in enumerate(segs[:-1]):
        size = (segs[si + 1] - seg) * 16
        code = mz.read(seg, 0, size)
        tables, targets = find_tables(md, code)
        starts = sorted({o for (s, o) in syms if s == seg} | targets | {0})
        data_end = {t: t + 2 * n for t, n in tables.items()}
        out.write(f'\n;================ segment {seg:04X} ({size:#x} bytes) ================\n')
        pc = 0
        while pc < size:
            if pc in tables:
                n = tables[pc]
                out.write(f'{seg:04X}:{pc:04X}  ; switch table, {n} cases\n')
                for i in range(n):
                    v = struct.unpack_from('<H', code, pc + 2 * i)[0]
                    out.write(f'{seg:04X}:{pc + 2 * i:04X}  dw {v:#06x}   ; case {i}\n')
                pc = data_end[pc]
                continue
            nxt = min([s for s in starts if s > pc] + [t for t in tables if t > pc] + [size])
            for ins in md.disasm(code[pc:nxt], pc):
                if ins.address in tables:
                    break
                key = (seg, ins.address)
                if key in syms:
                    note = f'   ; {notes[key]}' if key in notes else ''
                    out.write(f'\n{syms[key]}:{note}\n')
                elif ins.address in targets:
                    out.write(f'.case_{ins.address:04X}:\n')
                note = ''
                if ins.mnemonic in ('call', 'lcall'):
                    m = re.match(r'(0x[0-9a-f]+)(?:, (0x[0-9a-f]+))?$', ins.op_str)
                    if m:
                        tgt = ((int(m.group(1), 16), int(m.group(2), 16)) if m.group(2)
                               else (seg, int(m.group(1), 16)))
                        note = f'  ; {syms.get(tgt, "%04X:%04X" % tgt)}'
                else:
                    for m in re.finditer(r'0x([0-9a-f]+)', ins.op_str):
                        v = int(m.group(1), 16)
                        if v in strs and ins.mnemonic[0] != 'j':
                            note = f'  ; "{strs[v][:50]}"'
                        elif (DGROUP, v) in syms and '[' in ins.op_str:
                            note = f'  ; {syms[(DGROUP, v)]}'
                    g = grid_note(ins.op_str)
                    if g:
                        note = f'  ; {g}'
                out.write(f'{seg:04X}:{ins.address:04X}  {ins.bytes.hex():<16} '
                          f'{ins.mnemonic} {ins.op_str}{note}\n')
                pc = ins.address + ins.size
            pc = max(pc, nxt) if pc < nxt and nxt in tables else pc
            if pc < nxt:
                pc = nxt


if __name__ == '__main__':
    main()
